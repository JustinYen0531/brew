import assert from 'node:assert/strict';
import { buildRecipeSnapshot, promptForAttempt } from './daily-brew.mjs';
import { buildEditionRecipeResponse, publicRecipe } from '../api/edition-recipe.mjs';

const recipe = buildRecipeSnapshot('2026-08-21');
assert.equal(recipe.schema_version, 'daily-recipe-v1');
assert.equal(recipe.kind, 'automatic_daily_brew');
assert.equal(recipe.as_of_date, '2026-08-21');
assert.deepEqual(recipe.preferences.blend, { new_discoveries: 60, saved_reviews: 20, classic: 10, surprise: 10 });
assert.deepEqual(recipe.preferences.blend_ratios, recipe.preferences.blend);
assert.equal(recipe.preferences.output_language, 'zh-Hant');
assert.equal(recipe.preferences.timezone, 'Asia/Taipei');
assert.equal(recipe.preferences.morning_time, '07:00');
assert.deepEqual(recipe.preferences.topic_weights, {});
assert.equal(recipe.preferences.recipe_id, 'vibe-coding');
assert.equal(recipe.preferences.editorial_tone, 'hands-on-editor');
assert.equal(recipe.preferences.brew_method, 'daily-pour');
assert.equal(recipe.preferences.selected_source_ids.length, 10);
assert.equal(recipe.preferences.item_count, 10);
assert.equal(recipe.prompt.version, 'daily-prompt-v1');
assert.match(recipe.prompt.text, /資料截點也是 2026-08-21/);
assert.match(recipe.prompt.text, /Vibe Coding 入門/);
assert.match(promptForAttempt(recipe, 2), /第 2 次嘗試/);
assert.equal(recipe.search_rules.ranking_formula_version, 'v1');

const serialized = JSON.stringify(recipe);
assert.doesNotMatch(serialized, /OPENROUTER_API_KEY|OPENAI_API_KEY|SUPABASE_|service_role|sb_secret_/i);

const shared = publicRecipe(recipe);
assert.equal(shared.kind, 'automatic_daily_brew');
assert.equal(shared.prompt.text, recipe.prompt.text);
assert.equal(shared.preferences.recipe_id, 'vibe-coding');
assert.equal(shared.preferences.editorial_tone, 'hands-on-editor');
assert.deepEqual(shared.preferences.blend_ratios, recipe.preferences.blend);
assert.equal(shared.preferences.output_language, 'zh-Hant');
assert.equal(shared.preferences.morning_time, '07:00');
assert.equal('excluded_topics' in shared.preferences, false);
assert.equal(publicRecipe({ ...recipe, kind: 'manual_brew' }), null);
const response = buildEditionRecipeResponse({ id: 'edition-1', run_date: '2026-08-21', mode: 'daily', generated_at: '2026-08-21T06:00:00.000Z', generation_run_id: 'run-1', generation_run: { id: 'run-1', status: 'complete', attempts: [] }, items: [{ title: 'A', url: 'https://example.com/a', sourceType: 'Example' }], generation_recipe: recipe });
assert.equal(response.edition.generation_run_id, 'run-1');
assert.equal(response.generation.status, 'complete');
assert.equal(response.recipe.prompt.version, 'daily-prompt-v1');
assert.match(response.share.api_path, /edition-recipe/);
assert.equal(buildEditionRecipeResponse({ mode: 'historical', generation_recipe: recipe }), null);
const fakeSecret = `sk-${'a'.repeat(30)}`;
const redacted = buildEditionRecipeResponse({ id: 'edition-2', run_date: '2026-08-22', mode: 'daily', generation_run: { attempts: [{ number: 1, system: fakeSecret, user: `Bearer ${'b'.repeat(30)}` }] }, items: [], generation_recipe: { ...recipe, prompt: { ...recipe.prompt, text: `${recipe.prompt.text}\n${fakeSecret}` } } });
assert.doesNotMatch(JSON.stringify(redacted), new RegExp(fakeSecret));
assert.match(redacted.recipe.prompt.text, /已移除 API Key/);

console.log('daily recipe contract: OK');
